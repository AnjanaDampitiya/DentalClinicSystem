    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

    try {

        String name = jTextField2.getText().trim();
        String address = jTextField3.getText().trim();
        String contact = jTextField4.getText().trim();

        // 1. Required field validation
        if (name.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter Patient Name!"
            );

            jTextField2.requestFocus();
            return;
        }

        if (address.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter Address!"
            );

            jTextField3.requestFocus();
            return;
        }

        if (contact.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter Contact Number!"
            );

            jTextField4.requestFocus();
            return;
        }

        // 2. Patient name validation
        if (!name.matches("[a-zA-Z ]+")) {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient Name can contain letters and spaces only!"
            );

            jTextField2.requestFocus();
            return;
        }

        // 3. Contact validation
        if (!contact.matches("[0-9]{10}")) {

            JOptionPane.showMessageDialog(
                    this,
                    "Contact number must contain exactly 10 digits!"
            );

            jTextField4.requestFocus();
            return;
        }

        // 4. Create Patient object
        Patient patient = new Patient(
                0,
                name,
                address,
                contact
        );

        PatientController controller =
                new PatientController();

        // 5. Save patient
        boolean saved =
                controller.savePatient(patient);

        if (saved) {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient Saved Successfully!"
            );

            // Refresh table
            loadPatients();

            // Clear fields
            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
            jTextField4.setText("");

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "This patient is already saved!"
            );
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Database Error: " + e.getMessage()
        );
    }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {

        String idText = jTextField1.getText().trim();
        String name = jTextField2.getText().trim();
        String address = jTextField3.getText().trim();
        String contact = jTextField4.getText().trim();

        // 1. Patient ID validation
        if (idText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select a patient from the table first!"
            );

            return;
        }

        int id = Integer.parseInt(idText);

        if (id <= 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Invalid Patient ID!"
            );

            return;
        }

        // 2. Name validation
        if (name.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter Patient Name!"
            );

            jTextField2.requestFocus();
            return;
        }

        // 3. Address validation
        if (address.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter Address!"
            );

            jTextField3.requestFocus();
            return;
        }

        // 4. Contact validation
        if (contact.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter Contact Number!"
            );

            jTextField4.requestFocus();
            return;
        }

        // 5. Name format validation
        if (!name.matches("[a-zA-Z ]+")) {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient Name can contain letters and spaces only!"
            );

            jTextField2.requestFocus();
            return;
        }

        // 6. Contact format validation
        if (!contact.matches("[0-9]{10}")) {

            JOptionPane.showMessageDialog(
                    this,
                    "Contact number must contain exactly 10 digits!"
            );

            jTextField4.requestFocus();
            return;
        }

        // 7. Create Patient object
        Patient patient = new Patient(
                id,
                name,
                address,
                contact
        );

        PatientController controller =
                new PatientController();

        // 8. Update patient
        boolean updated =
                controller.updatePatient(patient);

        if (updated) {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient Updated Successfully!"
            );

            // Refresh table
            loadPatients();

            // Clear fields
            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
            jTextField4.setText("");

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient ID Not Found!"
            );
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Patient ID must be a valid number!"
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Database Error: " + e.getMessage()
        );
    }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {

        String idText = jTextField1.getText().trim();

        // 1. Patient ID empty check
        if (idText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select a patient from the table first!"
            );

            return;
        }

        // 2. Convert ID
        int id = Integer.parseInt(idText);

        // 3. Check ID is valid
        if (id <= 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Invalid Patient ID!"
            );

            return;
        }

        // 4. Confirmation
        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete this patient?",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        // 5. Delete patient
        PatientController controller =
                new PatientController();

        boolean deleted =
                controller.deletePatient(id);

        if (deleted) {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient Deleted Successfully!"
            );

            // Refresh table
            loadPatients();

            // Clear fields
            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
            jTextField4.setText("");

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Patient ID Not Found!"
            );
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Patient ID must be a valid number!"
        );

    } catch (java.sql.SQLIntegrityConstraintViolationException e) {

        JOptionPane.showMessageDialog(
                this,
                "Cannot delete this patient because this patient "
                + "is already used in an appointment."
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Database Error: " + e.getMessage()
        );
    }
    }//GEN-LAST:event_jButton3ActionPerformed

