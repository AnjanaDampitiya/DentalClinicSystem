    private void loadPatients() {

    try {

        Connection con = DriverManager.getConnection(
            "jdbc:mysql://localhost:3306/dental_clinic",
            "root",
            System.getenv("DENTAL_DB_PASSWORD")
        );

        String sql = "SELECT patient_id, patient_name, address, contact_number "
           + "FROM patients ORDER BY patient_id DESC";

        PreparedStatement pst = con.prepareStatement(sql);
        java.sql.ResultSet rs = pst.executeQuery();

        javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) jTable1.getModel();

        model.setRowCount(0);

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getInt("patient_id"),
                rs.getString("patient_name"),
                rs.getString("address"),
                rs.getString("contact_number")
            });
        }

        rs.close();
        pst.close();
        con.close();

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
            this,
            "Error loading patients: " + e.getMessage()
        );
    }
}
