    private void btnPatientTreatmentReportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPatientTreatmentReportActionPerformed


    try {

        DefaultTableModel model =
                (DefaultTableModel) tblDailyAppointments.getModel();

        model.setColumnIdentifiers(new String[]{
            "Patient ID",
            "Patient Name",
            "Treatment Name",
            "Description",
            "Fee"
        });

        model.setRowCount(0);

        List<String[]> treatments =
                reportController.getPatientTreatments();

        for (String[] row : treatments) {
            model.addRow(row);
        }

        lblDailyReportTitle.setText(
                "PATIENT TREATMENT REPORT"
        );

        lblTotalAppointments.setText(
                "Total Treatments: " + treatments.size()
        );

        lblReportDate.setText(
                "Report Date: "
                + java.time.LocalDate.now().toString()
        );

        if (treatments.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "No patient treatment records found."
            );
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error generating patient treatment report: "
                + e.getMessage()
        );
    }
    }//GEN-LAST:event_btnPatientTreatmentReportActionPerformed

