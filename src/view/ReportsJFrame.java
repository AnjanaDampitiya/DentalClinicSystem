    private void btnGenerateDailyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateDailyActionPerformed
       try {

    String today = java.time.LocalDate.now().toString();

    List<String[]> appointments =
            reportController.getDailyAppointments(today);

    DefaultTableModel model =
            (DefaultTableModel) tblDailyAppointments.getModel();

    model.setRowCount(0);

    for (String[] row : appointments) {
        model.addRow(row);
    }

    lblTotalAppointments.setText(
            "Total Appointments: " + appointments.size()
    );

    lblReportDate.setText(
            "Report Date: " + today
    );

    if (appointments.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "No appointments found for today."
        );
    }

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "Error generating report: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnGenerateDailyActionPerformed

    private void btnMonthlyReportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMonthlyReportActionPerformed
        try {

        // Change table columns
        DefaultTableModel model =
                (DefaultTableModel) tblDailyAppointments.getModel();

       model.setColumnIdentifiers(new String[]{
    "Bill ID",
    "Appointment ID",
    "Bill Date",
    "Amount",
    "Payment Status"
});

        model.setRowCount(0);

        // Get current month
        String month =
                java.time.LocalDate.now()
                        .format(
                            java.time.format.DateTimeFormatter.ofPattern("yyyy-MM")
                        );

        List<String[]> bills =
                reportController.getMonthlyRevenue(month);

        double totalRevenue = 0;

        for (String[] row : bills) {

            model.addRow(row);

            totalRevenue += Double.parseDouble(row[3]);
        }

        lblTotalAppointments.setText(
                "Total Bills: " + bills.size()
        );

        lblReportDate.setText(
                "Month: " + month
        );

        lblDailyReportTitle.setText(
                "MONTHLY REVENUE / BILLS REPORT"
        );

        if (bills.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "No bills found for this month."
            );
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error generating monthly report: "
                + e.getMessage()
        );
    }
    }//GEN-LAST:event_btnMonthlyReportActionPerformed

