    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
   

   
    try {

        // ==============================
        // 1. APPOINTMENT VALIDATION
        // ==============================

        if (cmbAppointment.getSelectedItem() == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select an Appointment!"
            );

            return;
        }

        String appointmentText =
                cmbAppointment.getSelectedItem().toString().trim();

        if (appointmentText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select an Appointment!"
            );

            return;
        }

        int appointmentId =
                Integer.parseInt(appointmentText);

        if (appointmentId <= 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Invalid Appointment ID!"
            );

            return;
        }


        // ==============================
        // 2. AMOUNT VALIDATION
        // ==============================

        String amountText =
                jTextField3.getText().trim();

        if (amountText.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter Bill Amount!"
            );

            jTextField3.requestFocus();
            return;
        }

        double amount =
                Double.parseDouble(amountText);

        if (amount <= 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Bill Amount must be greater than 0!"
            );

            jTextField3.requestFocus();
            return;
        }


        // ==============================
        // 3. BILL DATE VALIDATION
        // ==============================

        String billDate =
                jTextField4.getText().trim();

        if (billDate.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please enter Bill Date!"
            );

            jTextField4.requestFocus();
            return;
        }


        // ==============================
        // 4. PAYMENT STATUS VALIDATION
        // ==============================

        if (jComboBox1.getSelectedItem() == null) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select Payment Status!"
            );

            return;
        }

        String paymentStatus =
                jComboBox1.getSelectedItem()
                        .toString()
                        .trim();

        if (paymentStatus.isEmpty()
                || paymentStatus.equalsIgnoreCase("Select Status")) {

            JOptionPane.showMessageDialog(
                    this,
                    "Please select Payment Status!"
            );

            return;
        }


        // ==============================
        // 5. CREATE BILL
        // ==============================

        Bill bill = new Bill(
                0,
                appointmentId,
                amount,
                billDate,
                paymentStatus
        );


        // ==============================
        // 6. SAVE BILL
        // ==============================

        if (billController.saveBill(bill)) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Bill Saved Successfully!\nBill ID: "
                    + bill.getBillId()
            );

            clearFields();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Bill Save Failed!"
            );
        }


    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter valid Appointment ID and Amount!"
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Database Error: " + e.getMessage()
        );

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
        );
    }
    }//GEN-LAST:event_jButton1ActionPerformed

