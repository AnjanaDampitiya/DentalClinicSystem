    private void calculateAmount() {

    try {

        if (cmbAppointment.getSelectedItem() == null) {
            return;
        }

        int appointmentId =
                Integer.parseInt(
                    cmbAppointment.getSelectedItem().toString()
                );

        double total =
                billController.calculateTotalBill(appointmentId);

        jTextField3.setText(String.format("%.2f", total));

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error calculating bill: " + e.getMessage()
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Invalid Appointment ID!"
        );
    }
}
    
   private void loadAppointmentIds() {

    cmbAppointment.removeAllItems();

    try {

        List<Integer> ids = billController.getAppointmentIds();

        for (Integer id : ids) {
            cmbAppointment.addItem(String.valueOf(id));
        }

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Error loading Appointment IDs: " + e.getMessage()
        );
    }
}
