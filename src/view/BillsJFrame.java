    private void btnPrintActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPrintActionPerformed
        try {

        int selectedRow = tblBills.getSelectedRow();

        if (selectedRow == -1) {

            JOptionPane.showMessageDialog(
                this,
                "Please select a bill from the table first!"
            );

            return;
        }

        int billId = Integer.parseInt(
            tblBills.getValueAt(selectedRow, 0).toString()
        );

        int appointmentId = Integer.parseInt(
            tblBills.getValueAt(selectedRow, 1).toString()
        );

        double amount = Double.parseDouble(
            tblBills.getValueAt(selectedRow, 2).toString()
        );

        String billDate =
            tblBills.getValueAt(selectedRow, 3).toString();

        String paymentStatus =
            tblBills.getValueAt(selectedRow, 4).toString();

        double treatmentFee =
            billController.getTreatmentFee(appointmentId);

        double consultationFee = 1000.00;

        String receipt =
                "========================================\n"
              + "          SUNRISE DENTAL CLINIC\n"
              + "             BILL RECEIPT\n"
              + "========================================\n"
              + "Bill ID          : " + billId + "\n"
              + "Appointment ID   : " + appointmentId + "\n"
              + "Bill Date        : " + billDate + "\n"
              + "----------------------------------------\n"
              + "Treatment Cost   : Rs. "
              + String.format("%.2f", treatmentFee) + "\n"
              + "Consultation Fee : Rs. "
              + String.format("%.2f", consultationFee) + "\n"
              + "----------------------------------------\n"
              + "TOTAL            : Rs. "
              + String.format("%.2f", amount) + "\n"
              + "Payment Status   : " + paymentStatus + "\n"
              + "========================================\n"
              + "             Thank You!\n"
              + "========================================";

        javax.swing.JTextArea textArea =
            new javax.swing.JTextArea(receipt);

        textArea.setFont(
            new java.awt.Font(
                "Monospaced",
                java.awt.Font.PLAIN,
                12
            )
        );

        boolean complete =
            textArea.print();

        if (complete) {

            JOptionPane.showMessageDialog(
                this,
                "Bill printed successfully!"
            );

        } else {

            JOptionPane.showMessageDialog(
                this,
                "Printing was cancelled."
            );
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
            this,
            "Print Error: " + e.getMessage()
        );
    }
    }//GEN-LAST:event_btnPrintActionPerformed
private void loadBills() {

    try {

        List<Bill> bills = billController.getAllBills();

        DefaultTableModel model =
                (DefaultTableModel) tblBills.getModel();

        model.setRowCount(0);

        for (Bill bill : bills) {

            model.addRow(new Object[]{
                bill.getBillId(),
                bill.getAppointmentId(),
                bill.getAmount(),
                bill.getBillDate(),
                bill.getPaymentStatus()
            });
        }

    } catch (SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Database Error: " + e.getMessage()
        );
    }
}
